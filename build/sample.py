"""SAMPLE observations for the illustrative edition of the report.

WHAT THIS IS FOR
    Showing what the model produces once observations exist, so the approach
    can be agreed before the work of collecting them is done.

WHAT IT IS NOT
    An assessment.  Every value produced here is invented and is marked as such
    wherever it is shown: a banner on the page, a badge on every view, and a
    watermark behind the charts.

THE RULE THIS OBEYS
    Nothing here writes to facts/.  The sample values are generated in memory
    at build time and thrown away.  facts/observations.json keeps saying
    `unknown`, and out/management-report.html keeps saying nothing is rated.

    A previous version of this repository shipped `views_data.json` with
    invented scores in it.  It was quoted as though it were real.  That is the
    failure this module is built to avoid.
"""
import random


def sample_observations(m, seed=20260904):
    """Plausible-but-invented observations, in memory only.

    Generated by choosing a TARGET LEVEL per capability first, then working
    backwards to observations that produce it under the default ladder.
    Drawing each observation independently does not work: the scale requires
    all four to be strong for Level 2, so independent draws collapse almost
    everything to 0 and 1 and the charts show a wall of red that demonstrates
    nothing.

    The distribution is deliberately shaped to look like the finding the real
    assessment is expected to produce - platform and engineering ahead,
    governance and people behind, and practice trailing tooling.
    """
    rnd = random.Random(seed)
    # per domain: weights for landing at level 0 / 1 / 2 / 3
    MIX = {
        "D1": (.20, .45, .25, .10), "D2": (.15, .45, .30, .10),
        "D3": (.10, .35, .35, .20), "D4": (.10, .30, .35, .25),
        "D5": (.05, .25, .35, .35), "D6": (.15, .40, .30, .15),
        "D7": (.30, .45, .20, .05), "D8": (.25, .45, .25, .05),
    }
    DEFAULT_MIX = (.20, .40, .28, .12)

    def observations_for(level):
        """Four observations that derive to `level` under the default scale."""
        if level >= 3:
            return {"practised": "yes", "enabled": "yes",
                    "skilled": "yes", "defined": "yes"}
        if level == 2:
            # everything strong except a standard that is missing or pre-release
            return {"practised": "yes", "enabled": "yes", "skilled": "yes",
                    "defined": rnd.choice(["partial", "no"])}
        if level == 1:
            # performed, but one of tooling or competence is missing
            weak = rnd.choice(["enabled", "skilled", "both"])
            return {"practised": rnd.choice(["yes", "yes", "partial"]),
                    "enabled": "partial" if weak in ("enabled", "both")
                               else rnd.choice(["yes", "n/a"]),
                    "skilled": rnd.choice(["partial", "no"])
                               if weak in ("skilled", "both") else "yes",
                    "defined": rnd.choice(["yes", "partial", "no"])}
        # level 0 - not performed
        return {"practised": "no",
                "enabled": rnd.choice(["yes", "partial", "no", "n/a"]),
                "skilled": rnd.choice(["no", "partial"]),
                "defined": rnd.choice(["yes", "partial", "no"])}

    out = {}
    for c in m.capabilities:
        real = m.values(c['id'])
        lv = rnd.choices([0, 1, 2, 3], weights=MIX.get(c['domain'], DEFAULT_MIX))[0]
        v = observations_for(lv)
        # keep the one observation that is genuinely known today and cannot
        # contradict the level being demonstrated
        if real['enabled'] == 'n/a':
            v['enabled'] = 'n/a'
        out[c['id']] = v
    return out


def sample_targets(m, levels, top=3, seed=20260904):
    """A target level per capability, 12-month horizon. Invented."""
    rnd = random.Random(seed + 1)
    tgt = {}
    for c in m.capabilities:
        cur = levels.get(c['id'])
        base = 0 if cur is None else cur
        # governance and platform capabilities get pushed harder
        lift = 2 if c['domain'] in ("D5", "D7") else rnd.choice([1, 1, 2])
        tgt[c['id']] = min(top, base + lift)
    return tgt


class Demo(object):
    """The real model with SAMPLE observations layered on top.

    Wraps rather than copies, so every fact that is real - capabilities,
    offerings, assets, owners, criteria, sources - stays real and only the
    observations are substituted.  Nothing is written to facts/.
    """

    def __init__(self, m, obs):
        self._m = m
        self._obs = obs

    def __getattr__(self, k):
        return getattr(self._m, k)

    def values(self, cid):
        return dict(self._obs[cid])

    def rate(self, scale, cid):
        return scale.level(self.values(cid))

    def rate_all(self, scale):
        return {c['id']: self.rate(scale, c['id']) for c in self._m.capabilities}

    def cap_obs(self, cid, otype):
        return {'value': self._obs[cid].get(otype, 'unknown'),
                'evidence': 'sample', 'basis': 'sample'}

    def criteria_obs(self, cid, otype):
        """Sample criterion rows, consistent with the rolled-up L2 value."""
        rolled = self._obs[cid].get(otype, 'unknown')
        out = []
        for i, x in enumerate(self._m.by_id[cid]['criteria']):
            if rolled == 'yes':
                v = 'yes'
            elif rolled == 'no':
                v = 'no'
            elif rolled == 'n/a':
                v = 'n/a'
            elif rolled == 'partial':
                v = ('yes', 'no', 'yes', 'partial', 'unknown')[i % 5]
            else:
                v = 'unknown'
            out.append((x, {'value': v, 'evidence': 'sample', 'basis': 'sample'}))
        return out
