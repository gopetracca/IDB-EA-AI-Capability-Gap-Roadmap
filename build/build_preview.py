"""The views catalogue, rendered with SAMPLE observations.

WHAT THIS IS FOR
    Showing what the model produces once observations exist, so the approach can
    be agreed before the work of collecting them is done.

WHAT IT IS NOT
    An assessment. Every number on the page is invented by `sample_observations`
    below and marked as such: a banner on the page, a badge on every view, and a
    watermark behind the charts.

THE RULE THIS OBEYS
    Nothing here writes to facts/. The sample values are generated in memory at
    build time and thrown away. facts/observations.json keeps saying `unknown`,
    and out/management-report.html keeps saying nothing is rated.

    A previous version of this repository shipped `views_data.json` with invented
    scores in it. It was quoted as though it were real. That is the failure this
    file is built to avoid.
"""
import math
import random
import collections
from datetime import date

# Same analyst palette as the report: navy ramp, one warm accent.
C = {"yes": "#002869", "partial": "#4C8CD2", "no": "#E36135",
     "n/a": "#C9D2DA", "unknown": "#EDF1F4"}
LVL = {0: "#E36135", 1: "#9BB8DC", 2: "#4C8CD2", 3: "#0057AF",
       4: "#002869", 5: "#001B45", None: "#EDF1F4"}
ORDER = ["yes", "partial", "no", "n/a", "unknown"]
LABEL = {"yes": "Yes", "partial": "Partial", "no": "No",
         "n/a": "Not applicable", "unknown": "Not observed"}


def _shortname(name):
    n = name.replace("AI ", "", 1)
    return {"Governance, Risk, Security & Assurance":
            "Governance, Risk & Assurance"}.get(n, n)


def esc(s):
    return (str(s).replace("&", "&amp;").replace("<", "&lt;")
            .replace(">", "&gt;").replace('"', "&quot;"))


# ------------------------------------------------------------------ sample data
def sample_observations(m, seed=20260904):
    """Plausible-but-invented observations, in memory only.

    Generated by choosing a TARGET LEVEL per capability first, then working
    backwards to observations that produce it. Drawing each observation
    independently does not work: the scale requires all four to be strong for
    Level 2, so independent draws collapse almost everything to 0 and 1 and the
    charts show a wall of red that demonstrates nothing.

    The distribution is deliberately shaped to look like the finding the real
    assessment is expected to produce - platform and engineering ahead,
    governance and people behind, and practice trailing tooling.
    """
    rnd = random.Random(seed)
    # per domain: weights for landing at level 0 / 1 / 2 / 3
    MIX = {
        "D1": (.20, .45, .25, .10), "D2": (.15, .45, .30, .10),
        "D3": (.10, .35, .35, .20), "D4": (.10, .30, .35, .25),
        "D5": (.05, .25, .35, .35), "D6": (.15, .40, .30, .15),
        "D7": (.30, .45, .20, .05), "D8": (.25, .45, .25, .05),
    }

    def observations_for(level, enabled_real, defined_real):
        """Four observations that derive to `level` under the default scale."""
        if level >= 3:
            return {"practised": "yes", "enabled": "yes",
                    "skilled": "yes", "defined": "yes"}
        if level == 2:
            # everything strong except a standard that is missing or pre-release
            return {"practised": "yes", "enabled": "yes", "skilled": "yes",
                    "defined": rnd.choice(["partial", "no"])}
        if level == 1:
            # performed, but one of tooling or competence is missing
            weak = rnd.choice(["enabled", "skilled", "both"])
            return {"practised": rnd.choice(["yes", "yes", "partial"]),
                    "enabled": "partial" if weak in ("enabled", "both")
                               else rnd.choice(["yes", "n/a"]),
                    "skilled": rnd.choice(["partial", "no"])
                               if weak in ("skilled", "both") else "yes",
                    "defined": rnd.choice(["yes", "partial", "no"])}
        # level 0 - not performed
        return {"practised": "no",
                "enabled": rnd.choice(["yes", "partial", "no", "n/a"]),
                "skilled": rnd.choice(["no", "partial"]),
                "defined": rnd.choice(["yes", "partial", "no"])}

    out = {}
    for c in m.capabilities:
        real = m.values(c['id'])
        lv = rnd.choices([0, 1, 2, 3], weights=MIX[c['domain']])[0]
        v = observations_for(lv, real['enabled'], real['defined'])
        # keep the two observations that are genuinely known today, where doing
        # so does not contradict the level we are demonstrating
        if real['enabled'] == 'n/a':
            v['enabled'] = 'n/a'
        out[c['id']] = v
    return out


def sample_targets(m, levels, seed=20260904):
    """A target level per capability, 12-month horizon. Invented."""
    rnd = random.Random(seed + 1)
    tgt = {}
    for c in m.capabilities:
        cur = levels.get(c['id'])
        base = 0 if cur is None else cur
        # governance and platform capabilities get pushed harder
        lift = 2 if c['domain'] in ("D5", "D7") else rnd.choice([1, 1, 2])
        tgt[c['id']] = min(3, base + lift)
    return tgt


# ------------------------------------------------------------------ primitives
def wm(w, h, text="SAMPLE"):
    """Watermark behind a chart."""
    return ('<text x="%d" y="%d" class="wm" text-anchor="middle">%s</text>'
            % (w / 2, h / 2 + 12, text))


def legend(keys, labels=None, cols=None):
    labels = labels or LABEL
    cols = cols or C
    return ('<div class="legend">' + "".join(
        '<span><i style="background:%s"></i>%s</span>' % (cols[k], labels[k])
        for k in keys) + "</div>")


